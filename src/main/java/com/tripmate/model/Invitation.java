package com.tripmate.model;

import java.io.Serializable;
import java.util.Date;

/**
 * Model representing an invitation to collaborate on a trip.
 */
public class Invitation implements Serializable {
    private static final long serialVersionUID = 1L;

    private String id;
    private String tripId;
    private String tripTitle; // For UI display
    private String invitedBy; // userId
    private String inviterName; // For UI display
    private String inviteeEmail;
    private String role; // "EDITOR", "VIEWER"
    private String status; // "PENDING", "ACCEPTED", "DECLINED"
    private String invitationToken;
    private Date createdAt;

    public Invitation() {
        this.status = "PENDING";
        this.createdAt = new Date();
    }

    public String getId() {
        return id;
    }

    public void setId(String id) {
        this.id = id;
    }

    public String getTripId() {
        return tripId;
    }

    public void setTripId(String tripId) {
        this.tripId = tripId;
    }

    public String getTripTitle() {
        return tripTitle;
    }

    public void setTripTitle(String tripTitle) {
        this.tripTitle = tripTitle;
    }

    public String getInvitedBy() {
        return invitedBy;
    }

    public void setInvitedBy(String invitedBy) {
        this.invitedBy = invitedBy;
    }

    public String getInviterName() {
        return inviterName;
    }

    public void setInviterName(String inviterName) {
        this.inviterName = inviterName;
    }

    public String getInviteeEmail() {
        return inviteeEmail;
    }

    public void setInviteeEmail(String inviteeEmail) {
        this.inviteeEmail = inviteeEmail;
    }

    public String getRole() {
        return role;
    }

    public void setRole(String role) {
        this.role = role;
    }

    public String getStatus() {
        return status;
    }

    public void setStatus(String status) {
        this.status = status;
    }

    public String getInvitationToken() {
        return invitationToken;
    }

    public void setInvitationToken(String invitationToken) {
        this.invitationToken = invitationToken;
    }

    public Date getCreatedAt() {
        return createdAt;
    }

    public void setCreatedAt(Date createdAt) {
        this.createdAt = createdAt;
    }
}
